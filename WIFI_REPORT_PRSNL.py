def parse_args():
    p = argparse.ArgumentParser(description="Catalyst Center per-site PDF/CSV report")
    p.add_argument("--host", default=None, help="IP/hostname (or CATC_HOST env var)")
    p.add_argument("--user", default=None, help="Username (or CATC_USER env var)")
    p.add_argument("--password", default=None, help="Prefer CATC_PASSWORD env var or prompt")
    p.add_argument("--sites", default=None, help='Comma-separated SHORT site names, or "all"')
    p.add_argument("--hours", type=float, default=None, help="Window: last N hours")
    p.add_argument("--days", type=float, default=None, help="Window: last N days")
    p.add_argument("--start", default=None, help="Window start: YYYY-MM-DD[THH:MM] UTC")
    p.add_argument("--end", default=None, help="Window end (default: now minus data lag)")
    p.add_argument("--out", default=OUTPUT_PDF, help="Output PDF path")
    p.add_argument("--no-ap", action="store_true",
                   help="Skip per-AP RF collection (much faster on large sites)")
    p.add_argument("--debug", action="store_true", help="Verbose output + API key probing")
    return p.parse_args()


def resolve_credentials(args):
    host = args.host or os.environ.get("CATC_HOST")
    if not host:
        host = input("Catalyst Center IP/hostname: ").strip()
    if not host.startswith("http"):
        host = f"https://{host}"

    user = args.user or os.environ.get("CATC_USER")
    if not user:
        user = input("Username: ").strip()

    password = args.password or os.environ.get("CATC_PASSWORD")
    if not password:
        password = getpass.getpass("Password: ")

    return host, user, password


