def _aggregate_rows(rows):
    result = _empty_metrics()
    dhcp, auth, assoc, rssi, snr, onb = [], [], [], [], [], []
    roam_fail = roam_total = roam_ok = 0
    failed_clients = 0
    reasons = Counter()
    stages = Counter()
    probed = False

    for r in rows:
        o = r.get("onboarding", {}) or {}

        if DEBUG and not probed and o:
            log.info("onboarding block keys: %s", sorted(o.keys()))
            probed = True

        if o.get("avgDhcpDuration") is not None:
            dhcp.append(o["avgDhcpDuration"])
        if o.get("avgAuthDuration") is not None:
            auth.append(o["avgAuthDuration"])
        if o.get("avgAssocDuration") is not None:
            assoc.append(o["avgAssocDuration"])
        if o.get("avgRunDuration") is not None:
            onb.append(o["avgRunDuration"])

        roam_fail += o.get("failedRoamingCount", 0) or 0
        roam_ok += o.get("successfulRoamingCount", 0) or 0
        roam_total += o.get("totalRoamingAttempts", 0) or 0

        # Onboarding failure = any populated per-stage reason on this client
        hit = False
        for stage, key in _ONB_STAGES.items():
            if _is_failure(o.get(key)):
                stages[stage] += 1
                reasons[f"{stage}: {str(o[key]).strip()}"] += 1
                hit = True
        latest = o.get(_ONB_LATEST)
        if not hit and _is_failure(latest):
            stages["Unclassified"] += 1
            reasons[str(latest).strip()] += 1
            hit = True
        if hit:
            failed_clients += 1

        conn = r.get("connection", {}) or {}
        if conn.get("rssi") not in (0, None):
            rssi.append(conn["rssi"])
        if conn.get("snr") not in (0, None):
            snr.append(conn["snr"])

    avg = lambda L: (sum(L) / len(L)) if L else None
    result["avg_dhcp_time_ms"] = avg(dhcp)
    result["avg_auth_time_ms"] = avg(auth)
    result["avg_assoc_time_ms"] = avg(assoc)
    result["avg_rssi"] = avg(rssi)
    result["avg_snr"] = avg(snr)
    result["avg_onboarding_time_ms"] = avg(onb)
    result["client_count"] = len({r.get("macAddress") for r in rows})

    # Denominator is clients observed — the only honest one this release offers
    result["onboarding_fail_count"] = failed_clients if rows else None
    result["onboarding_total"] = len(rows) if rows else None
    result["onboarding_fail_reasons"] = "; ".join(
        f"{r} ({n})" for r, n in reasons.most_common(3))
    result["onboarding_fail_stages"] = "; ".join(
        f"{s}={n}" for s, n in stages.most_common())

    # Roaming: prefer reported total, else reconstruct from ok+failed
    result["roaming_fail_count"] = roam_fail
    result["roaming_success_count"] = roam_ok
    result["roaming_total"] = roam_total or (roam_ok + roam_fail)

    parts = [result["avg_onboarding_time_ms"], result["avg_dhcp_time_ms"],
             result["avg_auth_time_ms"], result["avg_assoc_time_ms"]]
    if all(v is not None for v in parts):
        result["avg_authz_delay_ms"] = max(0.0, parts[0] - (parts[1] + parts[2] + parts[3]))
    return result

