def export_to_csv(sites_payload, start_ms, end_ms, out_path="site_report.csv"):
    headers = [
        "Start Time", "End Time", "Site Name", "Hierarchy", "Controller", "Devices",
        "Site Tags", "RF Tags", "Policy Tags",
        "Band", "Client Count", "Avg RSSI (dBm)", "Avg SNR (dB)",
        "Avg Channel Util (%)",
        "Onboarding Time (ms)", "DHCP Time (ms)", "Auth Time (ms)",
        "Authz Delay (ms)", "Assoc Time (ms)",
        "Onboarding Failures", "Onboarding Attempts", "Onboarding Fail Rate (%)",
        "Roaming Failures", "Roaming Attempts", "Roaming Fail Rate (%)",
        "Top Onboarding Failure Reasons", "Onboarding Failure Stages"
    ]
    BAND_COL = headers.index("Band")

    start_str = datetime.utcfromtimestamp(start_ms / 1000).strftime('%Y-%m-%d %H:%M')
    end_str = datetime.utcfromtimestamp(end_ms / 1000).strftime('%Y-%m-%d %H:%M')

    existing_keys = set()
    file_exists = os.path.exists(out_path) and os.path.getsize(out_path) > 0
    if file_exists:
        with open(out_path, "r", newline="", encoding="utf-8-sig") as f:
            reader = csv.reader(f)
            next(reader, None)
            for row in reader:
                if len(row) > BAND_COL:
                    existing_keys.add(f"{row[0]}|{row[1]}|{row[2]}|{row[BAND_COL]}")

    with open(out_path, "a", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        if not file_exists:
            writer.writerow(headers)

        def write_if_unique(row_data, band):
            key = f"{start_str}|{end_str}|{row_data[2]}|{band}"
            if key not in existing_keys:
                writer.writerow(row_data)
                existing_keys.add(key)

        for sp in sites_payload:
            m = sp["metrics"]
            ctrl = sp.get("controller") or "N/A"
            devices = sp.get("devices") or "None"
            tagcols = [sp.get("site_tags", "—"), sp.get("rf_tags", "—"),
                       sp.get("policy_tags", "—")]

            write_if_unique([
                start_str, end_str, sp["name"], sp.get("hierarchy"), ctrl, devices,
                tagcols[0], tagcols[1], tagcols[2], "ALL",
                _fmt(m.get("client_count")), _fmt(m.get("avg_rssi")),
                _fmt(m.get("avg_snr")), _fmt(m.get("avg_channel_util")),
                _fmt(m.get("avg_onboarding_time_ms")), _fmt(m.get("avg_dhcp_time_ms")),
                _fmt(m.get("avg_auth_time_ms")), _fmt(m.get("avg_authz_delay_ms")),
                _fmt(m.get("avg_assoc_time_ms")),
                _fmt(m.get("onboarding_fail_count")), _fmt(m.get("onboarding_total")),
                _rate(m.get("onboarding_fail_count"), m.get("onboarding_total")),
                _fmt(m.get("roaming_fail_count")), _fmt(m.get("roaming_total")),
                _rate(m.get("roaming_fail_count"), m.get("roaming_total")),
                m.get("onboarding_fail_reasons") or "—",
                m.get("onboarding_fail_stages") or "—",
            ], "ALL")

            for band in _ordered_bands(sp.get("band_metrics", {})):
                if band.upper() == "UNKNOWN":
                    continue
                bm = sp["band_metrics"][band]
                write_if_unique([
                    start_str, end_str, sp["name"], sp.get("hierarchy"), ctrl, devices,
                    tagcols[0], tagcols[1], tagcols[2], band,
                    _fmt(bm.get("client_count")), _fmt(bm.get("avg_rssi")),
                    _fmt(bm.get("avg_snr")),
                    "—",   # util is per-radio; no reliable slot->band mapping
                    _fmt(bm.get("avg_onboarding_time_ms")), _fmt(bm.get("avg_dhcp_time_ms")),
                    _fmt(bm.get("avg_auth_time_ms")), _fmt(bm.get("avg_authz_delay_ms")),
                    _fmt(bm.get("avg_assoc_time_ms")),
                    _fmt(bm.get("onboarding_fail_count")), _fmt(bm.get("onboarding_total")),
                    _rate(bm.get("onboarding_fail_count"), bm.get("onboarding_total")),
                    _fmt(bm.get("roaming_fail_count")), _fmt(bm.get("roaming_total")),
                    _rate(bm.get("roaming_fail_count"), bm.get("roaming_total")),
                    bm.get("onboarding_fail_reasons") or "—",
                    bm.get("onboarding_fail_stages") or "—",
                ], band)

    log.info("CSV written: %s", out_path)
def export_ap_csv(sites_payload, start_ms, end_ms, out_path="site_report_aps.csv"):
    """One row per AP — the sheet that cross-references cleanly by tag."""
    headers = ["Start Time", "End Time", "Site Name", "Hierarchy", "AP Name",
               "Site Tag", "RF Tag", "Policy Tag", "Channel Util %",
               "Channel Changes", "Noise", "Interference", "Air Quality"]
    start_str = datetime.utcfromtimestamp(start_ms / 1000).strftime('%Y-%m-%d %H:%M')
