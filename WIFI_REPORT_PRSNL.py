def round_down_to_5min(ts_ms):
    return (ts_ms // 300000) * 300000


def epoch_ms_now():
    return int(datetime.utcnow().timestamp() * 1000)


def parse_user_datetime(s):
    for fmt in ("%Y-%m-%d %H:%M", "%Y-%m-%dT%H:%M", "%Y-%m-%d"):
        try:
            return datetime.strptime(s, fmt)
        except ValueError:
            continue
    raise SystemExit(f"Could not parse '{s}'. Use YYYY-MM-DD or YYYY-MM-DDTHH:MM (UTC).")


def prompt_for_time_window(now, earliest_allowed):
    print(f"\nNo time window specified (up to {MAX_LOOKBACK_DAYS} days back).")
    choice = input("Select window type:\n"
                   "  [1] Last N hours\n"
                   "  [2] Last N days\n"
                   "  [3] Specific start/end dates\n"
                   f"  [Enter] Default — last {WINDOW_HOURS}h\n> ").strip()
    if choice == "1":
        return now - timedelta(hours=float(input("Hours: ").strip())), now
    if choice == "2":
        return now - timedelta(days=float(input("Days: ").strip())), now
    if choice == "3":
        s = input("Start (YYYY-MM-DD or YYYY-MM-DDTHH:MM, UTC): ").strip()
        e = input("End [Enter = now]: ").strip()
        return (parse_user_datetime(s) if s else earliest_allowed,
                parse_user_datetime(e) if e else now)
    return now - timedelta(hours=WINDOW_HOURS), now


def resolve_time_window(args):
    now = datetime.utcnow() - timedelta(minutes=DATA_LAG_MINUTES)
    earliest = now - timedelta(days=MAX_LOOKBACK_DAYS)

    if (args.start or args.end) and (args.hours or args.days):
        raise SystemExit("Use either --start/--end OR --hours/--days, not both.")

    if args.start or args.end:
        start = parse_user_datetime(args.start) if args.start else earliest
        end = parse_user_datetime(args.end) if args.end else now
    elif args.hours:
        end, start = now, now - timedelta(hours=args.hours)
    elif args.days:
        end, start = now, now - timedelta(days=args.days)
    else:
        start, end = prompt_for_time_window(now, earliest)

    if end > now:
        log.warning("End %s newer than available data — clamping to %s", end, now)
        end = now
    if start < earliest:
        log.warning("Start %s exceeds %d-day retention — clamping to %s",
                    start, MAX_LOOKBACK_DAYS, earliest)
        start = earliest
    if start >= end:
        raise SystemExit(f"Start must precede end: start={start} end={end}")

    return (round_down_to_5min(int(start.timestamp() * 1000)),
            round_down_to_5min(int(end.timestamp() * 1000)))


def split_into_chunks(start_ms, end_ms, max_days=MAX_CHUNK_DAYS):
    chunk_ms = max_days * 24 * 3600 * 1000
    chunks, s = [], start_ms
    while s < end_ms:
        e = min(s + chunk_ms, end_ms)
        chunks.append((s, e))
        s = e
    return chunks


