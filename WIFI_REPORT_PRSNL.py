def _fetch_client_rows_chunk(c, site_id, start, end):
    body = {"startTime": start, "endTime": end, "page": {"limit": 500, "offset": 1}}
    try:
        resp = c.post("/dna/data/api/v1/clients/query", body,
                      params={"siteId": site_id}, retries=1)
    except requests.exceptions.HTTPError as e:
        if e.response is not None and e.response.status_code == 400:
            try:
                err = e.response.json().get("response", [{}])[0]
                code, msg = err.get("errorCode"), err.get("message", "")
                if code == 14006 and "endTime=" in msg:
                    m = re.search(r"endTime=(\d+)", msg)
                    if not m:
                        return []
                    body["endTime"] = int(m.group(1))
                    log.info("14006 data lag — retrying with endTime=%d", body["endTime"])
                    resp = c.post("/dna/data/api/v1/clients/query", body,
                                  params={"siteId": site_id}, retries=1)
                else:
                    log.debug("clients/query 400 for %s: %s", site_id, msg)
                    return []
            except Exception:
                return []
        else:
            log.debug("clients/query failed for %s: %s", site_id, e)
            return []
    except Exception as e:
        log.debug("clients/query error for %s: %s", site_id, e)
        return []

    records = resp.get("response", [])
    if not records:
        return []
    all_rows = list(records)
    offset = 501
    while len(records) == 500:
        body["page"]["offset"] = offset
        try:
            resp = c.post("/dna/data/api/v1/clients/query", body,
                          params={"siteId": site_id})
            records = resp.get("response", [])
            all_rows.extend(records)
            offset += 500
        except Exception as e:
            log.warning("Pagination failed at offset %d for %s: %s", offset, site_id, e)
            break
    return all_rows


