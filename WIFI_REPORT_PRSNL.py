def select_sites(all_sites, site_filter):
    if not site_filter or str(site_filter).strip().lower() == "all":
        return all_sites, []
    wanted = [n.strip().lower() for n in site_filter.split(",") if n.strip()]
    selected, matched = [], set()
    for s in all_sites:
        name = (s.get("name") or "").strip().lower()
        if name in wanted:
            selected.append(s)
            matched.add(name)
    dupes = [n for n, ct in Counter((s.get("name") or "").strip().lower()
                                    for s in selected).items() if ct > 1]
    if dupes:
        log.warning("Duplicate site name(s): %s — including all.", ", ".join(dupes))
    return selected, [w for w in wanted if w not in matched]


