def main():
    args = parse_args()
    global DEBUG
    if args.debug:
        DEBUG = True
        log.setLevel(logging.DEBUG)
        import catc_ap
        catc_ap.DEBUG = True          # turn on API key probing in the AP module

    # 1. Credentials
    host, user, password = resolve_credentials(args)
    c = CatalystClient(host, user, password, VERIFY_TLS)

    # 2. Time window (interactive menu if no flags given)
    start, end = resolve_time_window(args)
    window_str = (f"{datetime.utcfromtimestamp(start/1000):%Y-%m-%d %H:%M} -> "
                  f"{datetime.utcfromtimestamp(end/1000):%Y-%m-%d %H:%M} UTC")
    log.info("Report window: %s", window_str)

    # 3. Site discovery + selection
    site_filter = args.sites if args.sites is not None else SITE_FILTER
    all_sites = get_all_sites(c)
    if FLOORS_ONLY:
        all_sites = filter_floors(all_sites)
    sites, not_found = select_sites(all_sites, site_filter)

    if not_found:
        log.warning("No match for site name(s): %s", ", ".join(not_found))
    if not sites:
        log.error("No sites selected — check --sites. Exiting.")
        return

    site_health = get_site_health(c, epoch_ms_now())
    payload = []
    total = len(sites)

    # 4. Per-site collection
    for idx, s in enumerate(sites, 1):
        log.info("Processing site %d/%d: %s", idx, total, s["name"])

        sh = lookup_site_health(site_health, s["name"])
        device_list = get_site_devices(c, s["id"])
        device_list_str = "; ".join(device_list) if device_list else "None"

        detail_full = get_client_detail_agg(c, s["id"], start, end)
        detail = detail_full["ALL"]
        band_metrics = detail_full["by_band"]

        aps = [] if args.no_ap else get_ap_rf_stats(c, s["id"], start, end)
        tags = summarize_tags(aps)
        # if site-health has no controllerName/wlcName on 2.3.7.10 — resolve from inventory
        controller = (sh.get("controllerName") or sh.get("wlcName")
                      or get_site_controller(c, s["id"]))
        utils = [a["channel_util"] for a in aps if a.get("channel_util") is not None]
        ap_util_avg = (sum(utils) / len(utils)) if utils else None
        metrics = {
            "client_count": (detail["client_count"] or sh.get("numberOfClients")
                             or sh.get("clientCount")),
            "avg_channel_util": (sh.get("channelUtilization")
                                 or sh.get("avgChannelUtil")
                                 or ap_util_avg),
            "avg_rssi": (detail["avg_rssi"] if detail["avg_rssi"] is not None
                         else sh.get("clientRSSI")),
            "avg_snr": (detail["avg_snr"] if detail["avg_snr"] is not None
                        else sh.get("clientSNR")),
            "avg_onboarding_time_ms": detail["avg_onboarding_time_ms"],
            "avg_dhcp_time_ms": detail["avg_dhcp_time_ms"],
            "avg_auth_time_ms": detail["avg_auth_time_ms"],
            "avg_authz_delay_ms": detail["avg_authz_delay_ms"],
            "avg_assoc_time_ms": detail["avg_assoc_time_ms"],
            "chan_change_per_ap": ((sum(a["channel_changes"] for a in aps) / len(aps))
                                   if aps else "—"),
        }

        log.info("  clients=%s rssi=%s snr=%s dhcp=%s auth=%s assoc=%s "
                 "util=%s devices=%d aps=%d",
                 metrics["client_count"], metrics["avg_rssi"], metrics["avg_snr"],
                 metrics["avg_dhcp_time_ms"], metrics["avg_auth_time_ms"],
                 metrics["avg_assoc_time_ms"], metrics["avg_channel_util"],
                 len(device_list), len(aps))

        charts = [
            chart_rf_gauge(metrics["avg_channel_util"]),
            chart_rssi(metrics["avg_rssi"]),
            chart_snr(metrics["avg_snr"]),
            chart_delays_bar(detail["avg_dhcp_time_ms"], detail["avg_auth_time_ms"],
                             detail["avg_authz_delay_ms"], detail["avg_assoc_time_ms"]),
            chart_failures(detail["onboarding_fail_count"], detail["onboarding_total"],
                           detail["roaming_fail_count"], detail["roaming_total"]),
        ]
        if band_metrics:
            charts.extend([
                chart_rssi_by_band(band_metrics),
                chart_snr_by_band(band_metrics),
                chart_delays_by_band(band_metrics),
                chart_clients_by_band(band_metrics),
            ])
        charts.append(chart_util_by_ap(aps))

        # sorted by site tag so APs sharing a tag group together and outliers stand out
        ap_rows = [[a["name"], a.get("site_tag") or "—", a.get("rf_tag") or "—",
                    a.get("policy_tag") or "—", _fmt(a.get("channel_util")),
                    "/".join(f"{u:.0f}" for u in a.get("radio_util", [])) or "—",
                    str(a["channel_changes"]), _fmt(a.get("noise")),
                    _fmt(a.get("interference"))]
                   for a in sorted(aps, key=lambda x: (str(x.get("site_tag") or "~"),
                                                       x["name"]))]

        payload.append({
            "name": s["name"],
            "hierarchy": s["hierarchy"],
            "controller": controller,
            "devices": device_list_str,
            "metrics": metrics,
            "band_metrics": band_metrics,
            "charts": charts,
            "ap_rows": ap_rows,
            "site_tags": tags["site_tag"],
            "rf_tags": tags["rf_tag"],
            "policy_tags": tags["policy_tag"],
            "ap_detail": aps,
        })

    # 5. Output
    build_pdf(payload, args.out, window_str)
    csv_out = args.out.replace(".pdf", ".csv")
    export_to_csv(payload, start, end, csv_out)
    log.info("Done. Generated %s and %s", args.out, csv_out)


if __name__ == "__main__":
    main()