def _fmt(v, suffix=""):
    if v is None or v == "—":
        return "—"
    if isinstance(v, float):
        return f"{v:.1f}{suffix}"
    return f"{v}{suffix}"


def _rate(fail, total):
    """Percentage string, or em-dash when the denominator is unknown/zero."""
    if fail is None or not total:
        return "—"
    return f"{fail / total * 100:.1f}"

