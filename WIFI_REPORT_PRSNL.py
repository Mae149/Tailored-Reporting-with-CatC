def get_all_sites(c, max_sites=20000):
    seen, sites = set(), []
    offset, limit = 1, 500
    while True:
        try:
            data = c.get("/dna/intent/api/v1/site",
                         params={"offset": offset, "limit": limit})
        except Exception as e:
            log.warning("Error fetching sites at offset %d, retrying once...", offset)
            time.sleep(2)
            try:
                data = c.get("/dna/intent/api/v1/site",
                             params={"offset": offset, "limit": limit})
            except Exception:
                log.error("Failed to fetch sites: %s", e)
                break

        batch = data.get("response", [])
        if not batch:
            break
        new = 0
        for s in batch:
            sid = s.get("id")
            if not sid or sid in seen:
                continue
            seen.add(sid)
            new += 1
            sites.append({"id": sid, "name": s.get("name"),
                          "hierarchy": s.get("siteNameHierarchy") or s.get("groupNameHierarchy")})
        if len(batch) < limit or new == 0 or len(sites) >= max_sites:
            break
        offset += limit

    log.info("Discovered %d unique sites", len(sites))
    return sites


